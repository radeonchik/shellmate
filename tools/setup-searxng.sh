#!/usr/bin/env bash
# Local SearXNG for shellmate web search: installs from AUR (or re-tunes an existing install), 127.0.0.1 only,
# JSON API on, rate limiter off (it's just you), no valkey needed.
#   ./tools/setup-searxng.sh [agent-name]
set -euo pipefail

NAME="${1:-shellmate}"
PORT=8888
SETTINGS=/etc/searxng/settings.yml

step() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }

if ! command -v paru >/dev/null; then
    # SearXNG is packaged in the AUR only; elsewhere the official container is the easy way
    cat <<EOF2
Этот скрипт ставит SearXNG из AUR (Arch). На Debian/Ubuntu/Fedora проще через Docker/Podman:
  docker run -d --name searxng --restart unless-stopped -p 127.0.0.1:$PORT:8080 \\
    -e SEARXNG_BASE_URL=http://127.0.0.1:$PORT/ docker.io/searxng/searxng
затем включи JSON в /etc/searxng/settings.yml контейнера (search: formats: [html, json])
и пропиши в конфиг помощника: searx_url = "http://127.0.0.1:$PORT"
А надёжнее и проще всего — ключ Tavily: $NAME --search-setup
EOF2
    exit 1
fi

step "Ставлю searxng-git из AUR (сборка займёт пару минут)"
paru -S --needed searxng-git

step "Пишу $SETTINGS (только localhost, JSON включён)"
if [[ -f "$SETTINGS" ]] && ! sudo grep -q "shellmate" "$SETTINGS"; then
    sudo cp "$SETTINGS" "$SETTINGS.bak"
    echo "старый конфиг сохранён в $SETTINGS.bak"
fi
sudo tee "$SETTINGS" >/dev/null <<EOF
# generated by shellmate tools/setup-searxng.sh
use_default_settings: true
server:
  secret_key: "$(openssl rand -hex 32)"
  bind_address: "127.0.0.1"
  port: $PORT
  limiter: false
  public_instance: false
search:
  formats: [html, json]
valkey:
  url: false
outgoing:
  request_timeout: 4.0
# engines that answer from a home IP; DuckDuckGo keeps replying with a CAPTCHA (searxng#6596)
engines:
  - name: bing
    disabled: false
  - name: brave
    disabled: false
  - name: duckduckgo
    disabled: true
  - name: wikipedia
    disabled: false
EOF

step "Запускаю сервис"
sudo systemctl enable --now searxng
sudo systemctl restart searxng

step "Жду, пока поднимется"
for _ in $(seq 30); do
    curl -sf "http://127.0.0.1:$PORT/healthz" >/dev/null 2>&1 && break
    sleep 1
done
COUNT=$(curl -sf "http://127.0.0.1:$PORT/search?q=arch+linux&format=json" \
        | python3 -c 'import json,sys; print(len(json.load(sys.stdin)["results"]))' || echo 0)
if [[ "$COUNT" == 0 ]]; then
    echo "SearXNG не отвечает. Логи: journalctl -u searxng -n 50" >&2
    exit 1
fi
echo "работает: $COUNT результатов на тестовый запрос"

step "Подключаю к $NAME"
CONF="${XDG_CONFIG_HOME:-$HOME/.config}/$NAME/config.toml"
mkdir -p "$(dirname "$CONF")"
touch "$CONF"
if grep -q '^searx_url' "$CONF"; then
    sed -i "s|^searx_url.*|searx_url = \"http://127.0.0.1:$PORT\"|" "$CONF"
else
    echo "searx_url = \"http://127.0.0.1:$PORT\"" >> "$CONF"
fi
echo "Готово. Попробуй: $NAME найди в интернете, что нового в ядре 7.2"
